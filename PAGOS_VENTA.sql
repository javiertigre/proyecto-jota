-- ============================================================
-- PAGOS / ABONOS DE VENTAS EN DEUDA
-- Ejecutar en Supabase: SQL Editor
-- ------------------------------------------------------------
-- Cada abono es una fila nueva. NUNCA se sobrescribe el
-- depósito inicial de la venta.
--
--   saldo = precio_venta - deposito_cliente - SUM(abonos)
-- ============================================================

drop table if exists pagos_venta;

create table pagos_venta (
  id bigint generated by default as identity primary key,
  venta_id bigint not null references ventas(id) on delete cascade,
  producto_id bigint,                 -- dato de apoyo (sin FK para evitar choques de tipo)
  fecha_pago date not null,
  monto numeric(12,2) not null check (monto > 0),
  nota text,
  creado_por uuid default auth.uid(),
  created_at timestamptz default now()
);

create index if not exists idx_pagos_venta_venta on pagos_venta(venta_id);
create index if not exists idx_pagos_venta_fecha on pagos_venta(fecha_pago);

-- Mismo acceso que el resto del sistema
alter table pagos_venta enable row level security;
drop policy if exists "auth_full" on pagos_venta;
create policy "auth_full" on pagos_venta
  for all to authenticated
  using (true)
  with check (true);
